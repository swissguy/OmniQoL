--- Retrieves TM/HM list for a species from live Data or static fallback
function RelearnerData.getSpeciesTMHMs(species)
  local key = normKey(species)
  local okData, Data = pcall(require, "src.core.Data")
  if okData and Data and Data.pokemon and Data.pokemon[key] and Data.pokemon[key].tmhm then
    return Data.pokemon[key].tmhm
  end
  return RelearnerData.TMHM_LEARNSETS[key] or {}
end

--- Retrieves all eligible relearnable level-up (and optionally TM) moves for a Pokémon
-- @param mon Table { species = "...", level = N, moves = {...} }
-- @param mode string "RELEARN", "RELEARN+TMS", or "OFF"
-- @return table list of move candidate tables
function RelearnerData.getEligibleMoves(mon, mode)
  if not mon or not mon.species then return {} end

  mode = mode and tostring(mode):upper() or "RELEARN"
  if mode == "OFF" then return {} end

  local currentSpecies = normKey(mon.species)
  local currentLevel = tonumber(mon.level) or 100

  -- Build map of currently known moves to filter out
  local knownMoves = {}
  if type(mon.moves) == "table" then
    for _, mv in ipairs(mon.moves) do
      local mvName = type(mv) == "table" and (mv.id or mv.name) or mv
      if mvName then
        knownMoves[normKey(mvName)] = true
      end
    end
  end

  local eligibleList = {}
  local seenMoves = {}

  -- Stages to inspect: current species, followed by ancestors
  local stages = { currentSpecies }
  local ancestors = RelearnerData.getAncestors(currentSpecies)
  for _, anc in ipairs(ancestors) do
    table.insert(stages, anc)
  end

  -- 1. Level-up learnsets (all stages, level-gated)
  for _, stageSpecies in ipairs(stages) do
    local learnset = RelearnerData.LEARNSETS[stageSpecies]
    if learnset then
      for _, entry in ipairs(learnset) do
        local mName = normKey(entry.move)
        local reqLvl = entry.level or 1

        -- Level gate: must be <= current level OR a Level 1 starting move
        if (reqLvl <= currentLevel or reqLvl == 1) and not knownMoves[mName] and not seenMoves[mName] then
          seenMoves[mName] = true
          local meta = RelearnerData.MOVES[mName] or { type = "NORMAL", pp = 20 }
          table.insert(eligibleList, {
            name = mName,
            level = reqLvl,
            badge = (reqLvl == 1) and "Lv 1" or ("Lv" .. tostring(reqLvl)),
            type = meta.type or "NORMAL",
            pp = meta.pp or 20,
            isHM = meta.isHM or false,
            isTM = false,
            fromStage = stageSpecies,
          })
        end
      end
    end
  end

  -- 2. If mode includes TMs ("RELEARN+TMS" or "RELEARN+TM")
  if mode:find("TM") then
    local tmCandidates = {}
    for _, stageSpecies in ipairs(stages) do
      local tmList = RelearnerData.getSpeciesTMHMs(stageSpecies)
      for _, moveKey in ipairs(tmList) do
        local mName = normKey(moveKey)
        local tmCode = RelearnerData.TM_MOVES[mName]
        -- Must be valid TM (TM01-50), not HM, not already known, not already seen from level-up
        if tmCode and not RelearnerData.HM_MOVES[mName] and not knownMoves[mName] and not seenMoves[mName] then
          seenMoves[mName] = true
          local meta = RelearnerData.MOVES[mName] or { type = "NORMAL", pp = 20 }
          table.insert(tmCandidates, {
            name = mName,
            tmCode = tmCode,
            badge = tmCode,
            type = meta.type or "NORMAL",
            pp = meta.pp or 20,
            isHM = false,
            isTM = true,
            fromStage = stageSpecies,
          })
        end
      end
    end

    -- Sort TMs by TM number
    table.sort(tmCandidates, function(a, b)
      local numA = tonumber(a.tmCode:match("%d+")) or 999
      local numB = tonumber(b.tmCode:match("%d+")) or 999
      return numA < numB
    end)

    for _, tmMove in ipairs(tmCandidates) do
      table.insert(eligibleList, tmMove)
    end
  end

  return eligibleList
end

return RelearnerData
