-- ----------------------------------------------------------------------------
-- Helper Functions
-- ----------------------------------------------------------------------------

--- Normalizes a species or move key to uppercase without special characters
local function normKey(k)
  if not k then return "" end
  return tostring(k):upper():gsub("[^%w_]", "")
end

RelearnerData.normalizeKey = normKey

--- Retrieves all evolutionary ancestors in order (direct parent first)
-- @param species string
-- @return table list of ancestor species strings
function RelearnerData.getAncestors(species)
  local key = normKey(species)
  return RelearnerData.ANCESTRY[key] or {}
end

--- Retrieves all eligible relearnable level-up moves for a given Pokémon
-- Combines current species learnset + all prior evolutionary stage learnsets up to current level.
-- Excludes moves currently known by the Pokémon.
-- @param mon Table representing a Pokémon entity { species = "...", level = N, moves = {...} }
-- @return table list of move candidate tables { name = "...", type = "...", pp = N, level = N, stage = "..." }
function RelearnerData.getEligibleMoves(mon)
  if not mon or not mon.species then return {} end

  local currentSpecies = normKey(mon.species)
  local currentLevel = tonumber(mon.level) or 100

  -- Build map of currently known moves to filter out
  local knownMoves = {}
  if type(mon.moves) == "table" then
    for _, mv in ipairs(mon.moves) do
      local mvName = type(mv) == "table" and (mv.id or mv.name) or mv
      if mvName then
        knownMoves[normKey(mvName)] = true
      end
    end
  end

  local eligibleList = {}
  local seenMoves = {}

  -- Stages to inspect: current species, followed by ancestors
  local stages = { currentSpecies }
  local ancestors = RelearnerData.getAncestors(currentSpecies)
  for _, anc in ipairs(ancestors) do
    table.insert(stages, anc)
  end

  -- Traverse all stages
  for _, stageSpecies in ipairs(stages) do
    local learnset = RelearnerData.LEARNSETS[stageSpecies]
    if learnset then
      for _, entry in ipairs(learnset) do
        local mName = normKey(entry.move)
        local reqLvl = entry.level or 1

        -- Level gate: must be <= current level OR a Level 1 starting move
        if (reqLvl <= currentLevel or reqLvl == 1) and not knownMoves[mName] and not seenMoves[mName] then
          seenMoves[mName] = true
          local meta = RelearnerData.MOVES[mName] or { type = "NORMAL", pp = 20 }
          table.insert(eligibleList, {
            name = mName,
            level = reqLvl,
            type = meta.type or "NORMAL",
            pp = meta.pp or 20,
            isHM = meta.isHM or false,
            fromStage = stageSpecies,
          })
        end
      end
    end
  end

  return eligibleList
end

return RelearnerData
